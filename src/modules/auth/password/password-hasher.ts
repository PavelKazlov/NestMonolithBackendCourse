import { Injectable } from '@nestjs/common';
import * as argon2 from 'argon2';

/**
 * Параметры Argon2id — минимальная рекомендация OWASP Password Storage
 * Cheat Sheet: m = 19 MiB, t = 2, p = 1.
 *
 * - memoryCost (m) — сколько памяти (в KiB) занимает ОДНО вычисление хеша.
 *   Именно память делает Argon2 «неудобным» для GPU и ASIC: у видеокарты
 *   тысячи ядер, но мало памяти на каждое. Перебор паролей параллелится плохо.
 * - timeCost (t) — число проходов по этой памяти.
 * - parallelism (p) — число потоков на один хеш.
 *
 * Итог ≈ десятки миллисекунд на хеш. Для пользователя при входе это незаметно,
 * а для атакующего, который перебирает миллиарды паролей по утёкшей базе,
 * это годы вместо минут. В этом смысл «медленного» хеша.
 */
const ARGON2_OPTIONS = {
  type: argon2.argon2id,
  memoryCost: 19_456,
  timeCost: 2,
  parallelism: 1,
} as const;

/**
 * Хеширование паролей.
 *
 * Почему не SHA-256: он БЫСТРЫЙ (миллиарды в секунду на GPU), и без соли у
 * одинаковых паролей одинаковые хеши, а для таких есть готовые радужные таблицы.
 *
 * Argon2id:
 * - сам генерирует случайную соль (16 байт) для каждого вызова `hash`;
 * - кладёт соль и параметры в итоговую строку `$argon2id$v=19$m=...$<соль>$<хеш>`.
 * Поэтому два хеша одного пароля различаются, а `verify` берёт соль
 * и параметры прямо из сохранённой строки.
 *
 * Класс-обёртка нужен, чтобы сервисы не зависели от библиотеки напрямую.
 * В unit-тестах его легко подменить, а смена алгоритма затронет один файл.
 * `verify` понадобится в 1.2 (вход).
 */
@Injectable()
export class PasswordHasher {
  hash(password: string): Promise<string> {
    return argon2.hash(password, ARGON2_OPTIONS);
  }

  /**
   * Проверка пароля при входе: библиотека заново считает хеш введённого
   * пароля с солью и параметрами из `stored` и сравнивает результат
   * за постоянное время.
   */
  verify(stored: string, password: string): Promise<boolean> {
    return argon2.verify(stored, password);
  }
}
