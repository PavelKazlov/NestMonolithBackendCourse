import { Injectable, Logger } from '@nestjs/common';

/**
 * Значения полей аудита — только примитивы.
 *
 * Это ограничение типов, а не случайность. Если бы можно было передать объект,
 * рано или поздно кто-то написал бы `audit.info('...', { user })`, и в лог
 * уехала бы вся строка пользователя вместе с `passwordHash`. С примитивами
 * каждое поле приходится называть явно, и секрет «случайно» не проскочит.
 */
export type AuditValue = string | number | boolean | null | undefined;
export type AuditFields = Record<string, AuditValue | readonly string[]>;

/**
 * Журнал аудита: кто и что сделал с точки зрения безопасности
 * (регистрация, подтверждение, вход, смена ролей...).
 *
 * Чем аудит отличается от обычного лога:
 * - у каждой записи есть машинное имя события `event`
 *   (например, `registration.confirmation.failed`), по нему строят отчёты
 *   и алерты: «больше 100 неуспешных подтверждений за минуту»;
 * - записи пишутся всегда, а не только при отладке;
 * - в нём никогда нет секретов: ни паролей, ни хешей, ни кодов, ни токенов,
 *   ни тела запроса целиком (спека 1.0, раздел 1.5).
 *
 * Технически это тот же pino-логгер с контекстом `Audit`. Поэтому каждая запись
 * автоматически получает `requestId` текущего запроса, и по нему её можно
 * связать со строкой access-лога (метод, путь, статус).
 */
@Injectable()
export class AuditLogger {
  private readonly logger = new Logger('Audit');

  /** Успешное или нейтральное событие. */
  info(event: string, fields: AuditFields = {}): void {
    this.logger.log({ event, ...fields }, event);
  }

  /** Неуспех: отказ, неверный код, сбой отправки письма. */
  warn(event: string, fields: AuditFields = {}): void {
    this.logger.warn({ event, ...fields }, event);
  }
}
