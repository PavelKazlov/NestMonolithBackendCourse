import { Injectable } from '@nestjs/common';

import { ConfigService } from '@/core/config/config.service';
import { hmacSha256 } from '@/core/crypto/crypto.util';

/**
 * Необратимые служебные идентификаторы для журнала аудита.
 *
 * Спека 1.2 (раздел 1.5): «Для неизвестного email используется необратимый
 * служебный идентификатор с отдельным ключом, чтобы сопоставлять атаки без
 * записи адреса».
 *
 * Зачем это нужно. Атака перебором выглядит как сотни неуспешных входов на
 * один и тот же адрес. Чтобы это увидеть, записи надо как-то сгруппировать.
 * Писать email в журнал нельзя: это персональные данные, а журнал читает
 * больше людей, чем имеет доступ к БД. Поэтому пишем HMAC(email):
 * - один и тот же email всегда даёт один и тот же id, и записи группируются;
 * - по id нельзя восстановить email;
 * - перебрать «все популярные email» и сравнить хеши тоже нельзя: без ключа
 *   HMAC не посчитать (с обычным SHA-256 такой словарный перебор сработал бы).
 *
 * Ключ отдельный (`AUDIT_HMAC_KEY`): он нужен только журналу. Его утечка
 * не помогает подделать ни JWT, ни коды из писем.
 */
@Injectable()
export class AuditIds {
  private readonly key: string;

  constructor(config: ConfigService) {
    this.key = config.get('AUDIT_HMAC_KEY');
  }

  /**
   * Служебный id нормализованного email: первые 16 байт HMAC в hex (32 символа).
   * Укорачиваем ради читаемости журнала. 128 бит хватает, чтобы id разных
   * адресов практически никогда не совпадали.
   */
  emailId(email: string): string {
    return hmacSha256(this.key, `audit:email:${email}`)
      .subarray(0, 16)
      .toString('hex');
  }
}
